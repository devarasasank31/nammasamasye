export function normalizeText(text: string): string {
  let out = (text || '')
    .toLowerCase()
    .replace(/[‘’]/g, "'")
    .replace(/\s+/g, ' ')
    .trim();
  for (const [pattern, replacement] of TYPO_REPLACEMENTS) out = out.replace(pattern, replacement);
  return out;
}

export function detectLanguage(text: string): IncidentFacts['language'] {
  const kn = (text.match(/[\u0C80-\u0CFF]/g) || []).length;
  const hi = (text.match(/[\u0900-\u097F]/g) || []).length;
  const te = (text.match(/[\u0C00-\u0C7F]/g) || []).length;
  const latin = (text.match(/[a-z]/gi) || []).length;
  const counts: [IncidentFacts['language'], number][] = [
    ['kn', kn], ['hi', hi], ['te', te], ['en', latin],
  ];
  const significant = counts.filter(([, n]) => n >= 3);
  if (significant.length === 0) return 'und';
  significant.sort((a, b) => b[1] - a[1]);
  const top = significant[0];
  const runnerUp = significant[1];
  // Latin dominates → treat transliterations as English input.
  if (top[0] === 'en' && (!runnerUp || top[1] >= runnerUp[1] * 3)) return 'en';
  if (runnerUp && top[1] < runnerUp[1] * 1.5) return 'mixed';
  return top[0];
}

interface Match {
  concept: string;
  denied: boolean;
}

function matchConcepts(normalized: string): Match[] {
  const matches: Match[] = [];
  for (const [name, concept] of Object.entries(CONCEPTS)) {
    const hit = concept.patterns.some(p => p.test(normalized));
    if (!hit) continue;
    const denied = (concept.deny || []).some(p => p.test(normalized));
    matches.push({ concept: name, denied });
  }
  return matches;
}

function anyDenied(matches: Match[]): boolean {
  return matches.length > 0 && matches.every(m => m.denied);
}

const ALLEGATION_PATTERNS: { kind: 'intoxication' | 'other'; pattern: RegExp }[] = [
  { kind: 'intoxication', pattern: /\b(drunk|drinking|intoxicat\w*|under\s+the\s+influence|tipsy|high\s+on)\b/ },
  { kind: 'intoxication', pattern: /ಮದ್ಯ|ಕುಡಿದ|ಮತ್ತಿನ/ },
  { kind: 'intoxication', pattern: /शराब|नशे|मद्य/ },
  { kind: 'intoxication', pattern: /మద్యం|మత్తు/ },
  { kind: 'other', pattern: /\b(suspected|alleged|apparently|i\s+think|maybe|might\s+have\s+stolen)\b/ },
];

function parsePersistence(normalized: string): { days: number | null; recurring: boolean } {
  const recurring = /\b(every\s?day|daily|recurring|regularly|for\s+weeks|for\s+months|since\s+(last|january|february|march|april|may|june|july|august|september|october|november|december)|ನಿತ್ಯ|ಪ್ರತಿದಿನ|रोज़|रोज|हफ़्तों|महीनों|प्रतिदिन|రోజూ|ప్రతిరోజూ)/.test(normalized);
  const weeks = normalized.match(/\bfor\s+(\d+)\s+weeks?\b/);
  const months = normalized.match(/\bfor\s+(\d+)\s+months?\b/);
  const days = normalized.match(/\b(for|since)\s+(\d+)\s+days?\b/);
  const daysIndic = normalized.match(/(\d+)\s*(?:ದಿನ|ದಿನಗಳ|ದಿನದ|ದಿನಾ|ದಿನಾಗಿ|ದಿನಗಳಿಂದ|ದಿನದಿಂದ|ದಿನದಲ್ಲಿ|दिन|रोज़े|रोज़|रोज|रोजों|రోజు|రోజుల|రొజు|రొజుల|din|divas)/);
  if (months) return { days: Number(months[1]) * 30, recurring };
  if (weeks) return { days: Number(weeks[1]) * 7, recurring };
  if (days) return { days: Number(days[2]), recurring };
  if (daysIndic) return { days: Number(daysIndic[1]), recurring };
  if (recurring) return { days: 14, recurring: true };
  return { days: null, recurring: false };
}

function parsePeople(normalized: string): number | null {
  const explicit = normalized.match(/\b(\d{1,4})\s+(people|persons|men|women|children|kids|injured|trapped)\b/);
  if (explicit) return Number(explicit[1]);
  if (/\b(everyone|every\s+one|many\s+people|crowd|hundreds|thousands|whole\s+street|entire\s+(road|street|area|village)|all\s+people|numerous)\b/.test(normalized)) return 25;
  return null;
}

export function extractFacts(input: PriorityInput): IncidentFacts {
  const answers = input.answers || {};
  const base = normalizeText(`${input.text || ''} ${input.subcategory || ''} ${Object.values(answers).join(' ')}`);
  const normalized = base.replace(/[‘’]/g, "'");

  const matches = matchConcepts(normalized);
  const active = matches.filter(m => !m.denied);

  const resolvedNow = RESOLVED_PATTERNS.some(p => p.test(normalized)) || anyDenied(matches);
  const fictionContext = FICTION_PATTERNS.some(p => p.test(normalized));
  const historicalContext = HISTORICAL_PATTERNS.some(p => p.test(normalized));

  const injuries: InjuryFact[] = [];
  const has = (c: string) => active.some(m => m.concept === c);
  if (has('unconscious')) injuries.push({ kind: 'unconscious', basis: 'suspected' });
  if (has('fracture')) injuries.push({ kind: 'fracture', basis: 'suspected' });
  if (has('bleeding')) injuries.push({ kind: 'bleeding', basis: 'suspected' });
  if (has('injury')) injuries.push({ kind: 'general', basis: 'suspected' });
  // A dog bite wounds even when the citizen does not use the word "injured".
  const minorBite = /\b(?:no\s+(?:blood|bleeding)|nobody(?:\s+\w+){0,3}\s+hurt|it\s+is\s+not\s+serious|not\s+serious|minor\s+(?:bite|wound))\b/.test(normalized) ||
    matches.some(m => m.concept === 'bleeding' && m.denied);
  if (injuries.length === 0 && !minorBite && has('animal_attack') && /\b(bite|bit|bitten)\b/.test(normalized)) {
    injuries.push({ kind: 'general', basis: 'suspected' });
  }

  // Incident families from active concepts.
  const typeSet = new Set<IncidentType>();
  const standalone = new Set<IncidentType>();
  for (const m of active) {
    const fam = CONCEPT_TO_TYPE[m.concept];
    if (!fam) continue;
    if (PERSON_INJURY_CONCEPTS.has(m.concept)) standalone.add(fam);
    else typeSet.add(fam);
  }
  // Injury concepts only imply a collision when an accident/violence family
  // is also present, or when the injury words themselves appear with fall/
  // accident context; otherwise "I fell and broke my leg" still scores via
  // the injury dimension without being mislabelled as a vehicle collision.
  if (standalone.has('vehicle_collision') && (has('accident') || normalized.match(/\bfell\b|\bfall\b|\bslip/))) {
    typeSet.add('vehicle_collision');
  }
  if (standalone.has('physical_violence') && has('violence')) typeSet.add('physical_violence');
  if (typeSet.size === 0 && standalone.size > 0) {
    // Injury with no incident context at all → keep the injury family as the
    // incident type so routing still lands on a person-safety category.
    typeSet.add(has('violence') ? 'physical_violence' : 'vehicle_collision');
  }
  const incidentTypes = [...typeSet];

  // Related families describe ONE event (a collapse that traps people, a
  // burst sewer that floods the road); only unrelated families make a
  // report multi-incident.
  const familyGroup = (t: IncidentType): string => {
    if (['fire_explosion', 'structural_collapse', 'trapped_rescue', 'drowning', 'electrical_hazard', 'gas_chemical_hazard', 'vehicle_collision', 'physical_violence', 'animal_attack'].includes(t)) {
      return 'emergency';
    }
    if (t === 'sewage_contamination' || t === 'waterlogging') return 'water';
    return t;
  };
  const groups = new Set(incidentTypes.map(familyGroup));

  const incidentType: IncidentType = incidentTypes[0] || 'unknown';

  // Cause vs consequence: "sewer burst causing flooding", "water main
  // broke and that is why the road caved in" → route on the cause while
  // safety scoring still follows the visible danger.
  let causeType: IncidentType | null = null;
  const causeMatch = normalized.match(
    /\b(burst|bursting|broke|broken|blockage|leaking|leak)\b[^.!?]{0,80}?\b(causing|because|due\s+to|led\s+to|that\s+is\s+why|why)\b/
  );
  if (causeMatch) {
    const before = normalized.slice(Math.max(0, causeMatch.index! - 60), causeMatch.index! + causeMatch[0].length);
    if (/\b(water\s+main|water\s+pipe|pipeline|supply\s+pipe)\b/.test(before)) causeType = 'water_supply';
    else if (/\b(sewer|sewage|drain|drainage|manhole)\b/.test(before)) causeType = 'sewage_contamination';
    else if (/\b(wire|cable|electric|current|transformer)\b/.test(before)) causeType = 'electrical_hazard';
  }

  const allegations = ALLEGATION_PATTERNS.filter(a => a.pattern.test(normalized)).map(a => ({
    kind: a.kind,
    verified: false,
  }));

  const persistence = parsePersistence(normalized);
  const severeFlood =
    /\b(knee|waist|chest|hip|thigh)\s+deep\b|\b(road|street|lane)\b[^.!?]{0,45}\b(is\s+)?(closed|blocked|under\s+(water|the\s+water))\b|\bflooded\s+(homes|houses|ground\s+floors|shops)\b|ಮಂಡಿಮಟ್ಟ|ಕಾಲುಮಟ್ಟ|ರಸ್ತೆ[^.!?]{0,30}(ಬ್ಲಾಕ್|ಮುಚ್ಚಿದೆ|ಬಂದ್)|घुटनों\s+तक|रास्त[^.!?]{0,30}(बंद|ब्लॉक)|सड़क[^.!?]{0,30}(बंद|ब्लॉक)|మోకాళ్ల\s+లోతు|రోడ్డు[^.!?]{0,30}(బ్లాక్|మూసుకు)|\u0cb0\u0ccb\u0ca1\u0ccd\u0ca1\u0cc1[^.!?]{0,30}(ಬ್ಲಾಕ್|ಮುಚ್ಚಿದೆ|ಬಂದ್)/.test(normalized);

  // Severe electrical condition: a wire that is down/live/exposed/sparking
  // or an actual shock — in any supported language. The safety engine
  // requires this (not merely the word "wire") to force P1.
  const wireDown =
    (/\b(live|exposed|fallen|fell|snapped|broken|lying|down|sparking|touching|leaking)\b[^.!?]{0,45}\b(wire|cable|line|current|taar)\b/.test(normalized) ||
      /\b(wire|cable)\b[^.!?]{0,45}\b(fallen|fell|lying|broken|sparking|touching|on\s+the\s+(road|ground|water))\b/.test(normalized) ||
      /\b(electric(al)?\s+shock|electrocut\w*|shock\s+(lag|aa|ayi)|sparks?)\b/.test(normalized) ||
      /ವಿದ್ಯುತ್\s+(ತಂತಿ)[^.!?]{0,40}(ಬಿದ್ದ|ಸೋರ)/.test(normalized) ||
      /बिजली\s+(का)?\s+(तार|केबल)[^.!?]{0,40}(गिर|बिछ|टूट)/.test(normalized) ||
      /విద్యుత్\s+(తీగ|కేబుల్)[^.!?]{0,40}(పడి|జారి|తెగి)/.test(normalized) ||
      /taar\s+(gira|bidd|neechey)/.test(normalized) ||
      /ವಿದ್ಯುತ್\s+(ಶಾಕ್|ಆಘಾತ)|बिजली\s+(का)?\s+(झटका|करेंट)|విద్యుత్\s+షాక్/.test(normalized));

  const immediateDangerActive =
    !resolvedNow &&
    ((has('electrical') || has('fire') || has('collapse') || has('trapped') ||
      has('manhole') || has('gas_chemical') || has('drowning')) ||
      (severeFlood && (has('waterlogging') || has('sewage'))));
  const accidentDanger = !resolvedNow && has('accident') && injuries.length > 0;

  const incidentTypesAll = incidentTypes.length > 0 ? incidentTypes : (['unknown'] as IncidentType[]);

  return {
    normalized,
    language: detectLanguage(normalized),
    incidentType,
    incidentTypes: incidentTypesAll,
    multiIncident: groups.size > 1,
    causeType,
    injuries,
    accidentInvolved: has('accident'),
    openManhole: has('manhole'),
    wireDown,
    safetyDenied: anyDenied(matches),
    resolvedNow,
    historicalContext,
    fictionContext,
    allegations,
    peopleAffected: parsePeople(normalized),
    immediateDanger: immediateDangerActive || accidentDanger,
    imminentDanger:
      /\b(about\s+to\s+(fall|collapse)|may\s+collapse|leaning|could\s+fall|risk\s+of\s+collapse|accident[-\s](spot|prone)|dangerous\s+(spot|stretch|junction)|blind\s+(curve|turn)|unsafe\s+(spot|stretch))\b/.test(normalized),
    emergencyAccessBlocked:
      /\b(ambulance|fire\s+(truck|engine)|police)\b[^.!?,]{0,40}\b(blocked|cannot|can't|unable|no\s+access)\b/.test(normalized) ||
      /\b(blocked|blocked\s+completely|fully\s+blocked)\b[^.!?,]{0,60}\b(road|highway|street)\b/.test(normalized) ||
      /\b(road|street|lane|highway)\b[^.!?,]{0,45}\b(blocked|closed)\b/.test(normalized) ||
      /ರಸ್ತ[^.!?]{0,60}(ಬ್ಲಾಕ್|ಮುಚ್ಚಿದೆ)|ಬ್ಲಾಕ್[^.!?]{0,60}ರಸ್ತ|\u0cb0\u0ccb\u0ca1\u0ccd\u0ca1\u0cc1[^.!?]{0,60}(ಬ್ಲಾಕ್|ಮುಚ್ಚಿದೆ|ಬಂದ್)/.test(normalized) ||
      /(रास्त|सड़क)[^.!?]{0,60}(बंद|ब्लॉक)|ब्लॉक[^.!?]{0,60}(रास्त|सड़क)/.test(normalized) ||
      /రోడ్డు[^.!?]{0,60}(బ్లాక్|మూసుకు)|బ్లాక్[^.!?]{0,60}రోడ్డు/.test(normalized),
    vulnerableInvolved: /\b(children|kids|school|elderly|old\s+(people|man|woman)|disabled|wheelchair|pregnant|patients|toddlers|infants)\b/.test(normalized),
    infraCritical: /\b(hospital|school|college|airport|railway|metro|bridge|substation|water\s+(treatment|plant)|dam|court|police\s+station|fire\s+station)\b/.test(normalized),
    publicExposure: /\b(road|street|highway|main\s+road|junction|bus\s+stop|market|school|public|pedestrian|passers-by|neighbourhood|neighborhood|colony)\b/.test(normalized),
    persistenceDays: persistence.days,
    recurring: persistence.recurring,
    // Out of distribution = nothing recognisable at all. A report whose
    // only concepts are explicitly denied is understood (it just says
    // "no problem"), not unknown.
    outOfDistribution: incidentTypes.length === 0 && matches.length === 0,
  };
}
