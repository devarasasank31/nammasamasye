// ============================================================
// FACT EXTRACTION — normalise, detect language, pull the facts the
// safety engine and the scorer need.
//
// Rules that shape every pattern below:
//  * Negation matters: "there is no live wire" is NOT an electrical
//    hazard. Each concept carries its own deny patterns instead of a
//    global "not" toggle, so "no one was hurt" does not erase the wire.
//  * Resolved-state matters: "accident yesterday but everyone is fine
//    and the road is clear" must not read as an active emergency.
//  * Allegations are never facts: suspected intoxication etc. are
//    recorded as unverified and never asserted downstream.
//  * Injuries from free text are always "suspected" (unverified), and
//    uncertainty never downgrades a safety response.
// ============================================================

import { IncidentFacts, IncidentType, InjuryFact, PriorityInput } from './types';

