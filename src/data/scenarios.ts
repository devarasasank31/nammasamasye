export function getScenarioById(id: string): IncidentCategory | undefined {
  return scenarios.find(s => s.id === id);
}

export function getScenarioName(scenario: IncidentCategory, lang: Language): string {
  if (lang === 'kn' && scenario.nameKn) return scenario.nameKn;
  if (lang === 'hi' && scenario.nameHi) return scenario.nameHi;
  if (lang === 'te' && scenario.nameTe) return scenario.nameTe;
  return scenario.name;
}

export function getAllCategories(): CategoryParent[] {
  return [...new Set(scenarios.map(s => s.parent))];
}
